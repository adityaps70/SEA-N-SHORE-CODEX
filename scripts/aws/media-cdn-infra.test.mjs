import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
import { guardAction } from './guard-value.mjs'

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8')
const terraform = read('../../infra/aws/app/media-cdn.tf')
const bucketPolicies = read('../../infra/aws/app/bucket-policies.tf')
const edge = read('../../infra/aws/app/edge.tf')
const script = read('./media-cdn-infra.sh')
const workflow = read('../../.github/workflows/aws-media-cdn-infra.yml')

test('the media CDN key is ECDSA P-256, generated by Terraform and kept in Secrets Manager', () => {
  assert.match(terraform, /resource "tls_private_key" "media_cdn" \{\s+algorithm\s+= "ECDSA"\s+ecdsa_curve = "P256"/)
  assert.match(terraform, /secret_string = tls_private_key\.media_cdn\.private_key_pem_pkcs8/)
  assert.match(terraform, /encoded_key = tls_private_key\.media_cdn\.public_key_pem/)
  assert.match(terraform, /items\s+= \[aws_cloudfront_public_key\.media_cdn\.id\]/)
  assert.match(terraform, /Action\s+= \["secretsmanager:GetSecretValue"\]/)
  assert.doesNotMatch(terraform, /secretsmanager:\*|PutSecretValue|DeleteSecret/)
  assert.doesNotMatch(terraform, /output "[^"]*"\s*\{[^}]*private_key/, 'the private key is never an output')
})

test('the bucket stays private and only the app distribution may read the m/ prefix', () => {
  assert.match(bucketPolicies, /Principal = \{ Service = "cloudfront\.amazonaws\.com" \}/)
  assert.match(bucketPolicies, /Action\s+= "s3:GetObject"/)
  assert.match(bucketPolicies, /Resource\s+= "\$\{each\.value\.arn\}\/m\/\*"/)
  assert.match(bucketPolicies, /Condition = \{ StringEquals = \{ "AWS:SourceArn" = local\.app_distribution_arn \} \}/)
  assert.match(terraform, /app_distribution_id\s+= "EF1K45UVP11XZ"/)
  assert.match(terraform, /signing_behavior\s+= "always"/)
  assert.match(terraform, /signing_protocol\s+= "sigv4"/)
})

test('the edge serves /m/* only to signed requests, path-keyed, with no viewer function', () => {
  const behavior = edge.slice(edge.indexOf('path_pattern           = "/m/*"'), edge.indexOf('path_pattern           = "/_next/static/*"'))
  assert.match(behavior, /trusted_key_groups\s+= \[aws_cloudfront_key_group\.media_cdn\.id\]/)
  assert.match(behavior, /allowed_methods\s+= \["GET", "HEAD"\]/)
  assert.match(behavior, /cache_policy_id\s+= aws_cloudfront_cache_policy\.media_cdn\.id/)
  assert.doesNotMatch(behavior, /function_association|origin_request_policy_id/)
  assert.match(edge, /origin_access_control_id = aws_cloudfront_origin_access_control\.media\.id/)
  const policy = terraform.slice(terraform.indexOf('resource "aws_cloudfront_cache_policy" "media_cdn"'))
  assert.match(policy, /cookie_behavior = "none"/)
  assert.match(policy, /header_behavior = "none"/)
  assert.match(policy, /query_string_behavior = "none"/)
})

test('the runner allows only the signed-media changes and proves the path before enabling signing', () => {
  assert.ok(['plan', 'apply-once', 'enable-once', 'disable-once'].includes(guardAction(read('./media-cdn-infra-action.txt'))))
  assert.match(script, /plan\|apply-once\|enable-once\|disable-once/)
  assert.match(script, /The media bucket policy may only gain the CloudFront read of m\/\*/)
  assert.match(script, /Unexpected change:/)
  assert.match(script, /bash scripts\/aws\/branch-head\.sh refs\/heads\/feat\/aws-native-phase-0-1/)
  // Enabling needs the edge behavior and the backfill's probe, then a real signed request through CloudFront;
  // unsigned, wrong-folder and tampered requests, and a direct bucket request, must all be refused.
  assert.match(script, /The \/m\/\* edge behavior is not live yet; run the edge apply first\./)
  assert.match(script, /The backfill probe is missing; run the media CDN backfill first\./)
  assert.match(script, /MEDIA_CDN_SIGNED_PATH_VERIFIED=true/)
  assert.equal((script.match(/!= 403|== 403/g) ?? []).length, 4)
  assert.match(script, /openssl dgst -sha256 -sign "\$key_file"/)
  assert.match(script, /Hash-Algorithm=SHA256/)
  assert.match(script, /rm -f "\$key_file"/)
  assert.doesNotMatch(script, /cat "\$key_file"|echo "\$\(cat/, 'the key is never printed')
  // The web task gets the secret and key id as a new revision; the running service is not changed here.
  assert.match(script, /"name":"MEDIA_CDN_SIGNING_KEY","valueFrom":\$secret/)
  assert.match(script, /"name":"MEDIA_CDN_KEY_PAIR_ID","value":\$key/)
  assert.match(script, /aws ecs register-task-definition/)
  assert.doesNotMatch(script, /aws ecs update-service|delete-secret|delete-bucket-policy|put-bucket-policy/)
})

test('the workflow runs only from the feature branch, behind the owner-merged arm and staging-apply', () => {
  assert.match(workflow, /bash scripts\/aws\/arm-commit-guard\.sh/)
  assert.match(workflow, /environment: staging-apply/)
  assert.match(workflow, /node scripts\/aws\/media-cdn-infra\.test\.mjs/)
  assert.match(workflow, /MEDIA_CDN_INFRA_EXPECTED_SHA/)
  assert.match(workflow, /MEDIA_CDN_SIGNING_ENABLED_FOR_NEXT_DEPLOY=true/)
})
